//! The client's table-based float approximations (`Base\Rtl\Math`).
//!
//! Both work on the bit pattern of an f32 with a 256-entry mantissa table
//! (tables copied from Gw.exe build 38888). Pathing generation depends on
//! them, so they are reproduced bit for bit.

/// Fast `1 / sqrt(x)` (`0x46e530`).
pub fn rsqrt(x: f32) -> f32 {
    let b = x.to_bits();
    let index = (b >> 16) & 0xFF;
    f32::from_bits(
        RSQRT_TABLE[index as usize]
            .wrapping_sub((b >> 24).wrapping_mul(0x80_0000))
            .wrapping_add(0x5E80_0000),
    )
}

/// Fast `1 / x` (`0x46e500`).
pub fn recip(x: f32) -> f32 {
    let b = x.to_bits();
    let index = (b & 0x7F_FFFF) >> 15;
    f32::from_bits(RECIP_TABLE[index as usize].wrapping_sub((b & 0xFF80_0000).wrapping_add(0x817F_FFFF)))
}

