#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn approximates() {
        for x in [0.25f32, 1.0, 2.0, 3.0, 96.0 * 96.0, 12345.678, 1.0e8] {
            let r = rsqrt(x);
            assert!((r - 1.0 / x.sqrt()).abs() / (1.0 / x.sqrt()) < 1e-2, "rsqrt({x}) = {r}");
            let q = recip(x);
            assert!((q - 1.0 / x).abs() / (1.0 / x) < 1e-2, "recip({x}) = {q}");
        }
    }
}
